// Converts real-world circuit GeoJSON (lon/lat) into local metric centerlines for the game.
// Source data: https://github.com/bacinger/f1-circuits (MIT)
import fs from 'node:fs';
import path from 'node:path';
import url from 'node:url';

const dir = path.dirname(url.fileURLToPath(import.meta.url));
const ids = ['it-1922', 'be-1925', 'gb-1948', 'az-2016', 'mc-1929', 'at-1969'];
const out = {};
let svg = '';

for (const id of ids) {
  const gj = JSON.parse(fs.readFileSync(path.join(dir, id + '.geojson'), 'utf8'));
  const f = gj.features[0];
  let coords = f.geometry.coordinates;
  const lat0 = coords.reduce((a, c) => a + c[1], 0) / coords.length;
  const lon0 = coords.reduce((a, c) => a + c[0], 0) / coords.length;
  const R = 6378137;
  let pts = coords.map(([lon, lat]) => [
    (lon - lon0) * Math.PI / 180 * R * Math.cos(lat0 * Math.PI / 180),
    -(lat - lat0) * Math.PI / 180 * R,
  ]);
  // drop closing duplicate
  const a = pts[0], b = pts[pts.length - 1];
  if (Math.hypot(a[0] - b[0], a[1] - b[1]) < 1) pts.pop();
  // remove near-duplicates
  pts = pts.filter((p, i) => i === 0 || Math.hypot(p[0] - pts[i - 1][0], p[1] - pts[i - 1][1]) > 0.5);

  // resample closed polyline at fixed spacing
  const resample = (P, step) => {
    const n = P.length;
    const res = [];
    let carry = 0;
    for (let i = 0; i < n; i++) {
      const p = P[i], q = P[(i + 1) % n];
      const L = Math.hypot(q[0] - p[0], q[1] - p[1]);
      let t = carry;
      while (t < L) {
        const k = t / L;
        res.push([p[0] + (q[0] - p[0]) * k, p[1] + (q[1] - p[1]) * k]);
        t += step;
      }
      carry = t - L;
    }
    return res;
  };
  let r = resample(pts, 2);
  // gentle smoothing to remove GPS jaggies, keep shape
  for (let it = 0; it < 6; it++) {
    const n = r.length;
    r = r.map((p, i) => {
      const s = [0, 0];
      let w = 0;
      for (let k = -3; k <= 3; k++) {
        const q = r[(i + k + n) % n];
        const wk = 4 - Math.abs(k);
        s[0] += q[0] * wk; s[1] += q[1] * wk; w += wk;
      }
      return [s[0] / w, s[1] / w];
    });
  }
  let len = 0;
  for (let i = 0; i < r.length; i++) {
    const p = r[i], q = r[(i + 1) % r.length];
    len += Math.hypot(q[0] - p[0], q[1] - p[1]);
  }
  const official = f.properties.length;
  const scale = official / len;
  r = r.map(p => [p[0] * scale, p[1] * scale]);
  let fin = resample(r, 8);
  // rotate so index 0 is the real start/finish line
  const startFrac = { 'mc-1929': 0.735 }[id] || 0;
  if (startFrac) {
    const k = Math.round(fin.length * startFrac);
    fin = fin.slice(k).concat(fin.slice(0, k));
  }
  let area = 0;
  for (let i = 0; i < fin.length; i++) {
    const p = fin[i], q = fin[(i + 1) % fin.length];
    area += p[0] * q[1] - q[0] * p[1];
  }
  // In x=east, z=south coords, positive shoelace => clockwise when viewed on a north-up map
  console.log(id, f.properties.Name, 'raw', len.toFixed(0), 'official', official, 'pts', fin.length, area > 0 ? 'CW' : 'CCW');
  out[id] = { name: f.properties.Name, location: f.properties.Location, length: official, points: fin.map(p => [+p[0].toFixed(2), +p[1].toFixed(2)]) };

  // debug svg
  const xs = fin.map(p => p[0]), zs = fin.map(p => p[1]);
  const minx = Math.min(...xs), maxx = Math.max(...xs), minz = Math.min(...zs), maxz = Math.max(...zs);
  const sc = 380 / Math.max(maxx - minx, maxz - minz);
  const d = fin.map((p, i) => (i ? 'L' : 'M') + ((p[0] - minx) * sc + 10).toFixed(1) + ' ' + ((p[1] - minz) * sc + 10).toFixed(1)).join(' ') + 'Z';
  const mk = (i, c) => `<circle cx="${((fin[i][0] - minx) * sc + 10).toFixed(1)}" cy="${((fin[i][1] - minz) * sc + 10).toFixed(1)}" r="5" fill="${c}"/>`;
  const ticks = [];
  for (let k = 1; k < 10; k++) {
    const i = Math.floor(fin.length * k / 10);
    ticks.push(`<text x="${((fin[i][0] - minx) * sc + 14).toFixed(1)}" y="${((fin[i][1] - minz) * sc + 10).toFixed(1)}" font-size="12" fill="#ff0">${k / 10}</text>`);
  }
  svg += `<div style="display:inline-block;margin:6px;background:#222"><div style="color:#fff">${id} ${f.properties.Name}</div><svg width="400" height="400"><path d="${d}" stroke="#fff" fill="none" stroke-width="2"/>${mk(0, 'lime')}${mk(5, 'red')}${ticks.join('')}</svg></div>`;
}

fs.writeFileSync(path.join(dir, '..', 'js', 'trackdata.js'),
  '// Generated by tools/build-tracks.mjs from real circuit geometry (github.com/bacinger/f1-circuits, MIT license)\nexport const TRACK_DATA = ' + JSON.stringify(out) + ';\n');
fs.writeFileSync(path.join(dir, 'preview.html'), `<body style="background:#111">${svg}</body>`);
